export interface SuggestedPromptItem {
  id: string;
  text: string;
  englishText: string;
  actionType?: PromptDefinition["actionType"];
  isSeasonal?: boolean;
}

export function getSuggestedPrompts(
  role: UserRole,
  sectionContext: string = "default",
  currentLanguage: LanguageCode = "en",
  pendingActionTitle?: string
): SuggestedPromptItem[] {
  // Normalize section context to valid section tags
  let normalizedSection = sectionContext.toLowerCase().trim();

  // Normalize mapping
  if (
    normalizedSection === "bottom_nav" ||
    normalizedSection === "none" ||
    normalizedSection === "" ||
    normalizedSection === "default"
  ) {
    normalizedSection = "default";
  } else if (
    normalizedSection === "disease_camera" ||
    normalizedSection === "camera" ||
    normalizedSection === "plant_doctor"
  ) {
    normalizedSection = "disease_scan";
  } else if (normalizedSection === "iot_sensors" || normalizedSection === "iot") {
    normalizedSection = "smart_sensors";
  } else if (normalizedSection === "market_prices" || normalizedSection === "prices") {
    normalizedSection = "mandi_rates";
  } else if (
    normalizedSection === "yield_prediction" ||
    normalizedSection === "yield" ||
    normalizedSection === "yield_report"
  ) {
    normalizedSection = "yield_prediction";
  } else if (
    normalizedSection === "fertilizer_recommend" ||
    normalizedSection === "fertilizer"
  ) {
    normalizedSection = "fertilizer_recommend";
  } else if (
    normalizedSection === "job_feed" ||
    normalizedSection === "feed" ||
    normalizedSection === "jobs"
  ) {
    normalizedSection = role === "labour" ? "job_feed" : "default";
  } else if (
    normalizedSection === "skills" ||
    normalizedSection === "profile" ||
    normalizedSection === "profile_skills"
  ) {
    normalizedSection = role === "labour" ? "profile_skills" : "default";
  } else if (
    normalizedSection === "applied" ||
    normalizedSection === "applied_saved" ||
    normalizedSection === "applied_jobs"
  ) {
    normalizedSection = role === "labour" ? "applied_jobs" : "default";
  } else if (
    normalizedSection === "overview" ||
    normalizedSection === "dashboard"
  ) {
    normalizedSection = role === "fpo" ? "dashboard" : "home";
  } else if (normalizedSection === "members") {
    normalizedSection = "members";
  } else if (normalizedSection === "reports") {
    normalizedSection = "reports";
  } else if (normalizedSection === "broadcast") {
    normalizedSection = "broadcast";
  } else if (normalizedSection === "plants" || normalizedSection === "my_plants") {
    normalizedSection = "plants";
  } else if (normalizedSection === "water") {
    normalizedSection = "water";
  }

  // Filter catalog by role and section
  let matchingPrompts = SUGGESTED_PROMPT_CATALOG.filter(
    (p) => p.role === role && p.section === normalizedSection
  );

  // If no matching section found, fallback to role's default prompts
  if (matchingPrompts.length === 0) {
    matchingPrompts = SUGGESTED_PROMPT_CATALOG.filter(
      (p) => p.role === role && p.section === "default"
    );
  }

  const result: SuggestedPromptItem[] = matchingPrompts.map((p) => ({
    id: p.id,
    text: p.translations[currentLanguage] || p.translations.en || p.translations.hi,
    englishText: p.translations.en,
    actionType: p.actionType,
    isSeasonal: p.isSeasonal,
  }));

  // If pending action exists for Farmer default/home, surface as prompt
  if (role === "farmer" && (normalizedSection === "default" || normalizedSection === "home") && pendingActionTitle) {
    const dynamicPromptText =
      currentLanguage === "hi"
        ? `${pendingActionTitle} के बारे में बताएं`
        : currentLanguage === "te"
        ? `${pendingActionTitle} గురించి చెప్పండి`
        : currentLanguage === "ta"
        ? `${pendingActionTitle} பற்றி கூறுங்கள்`
        : currentLanguage === "mr"
        ? `${pendingActionTitle} बद्दल सांगा`
        : currentLanguage === "pa"
        ? `${pendingActionTitle} ਬਾਰੇ ਦੱਸੋ`
        : currentLanguage === "bn"
        ? `${pendingActionTitle} সম্পর্কে বলুন`
        : currentLanguage === "kn"
        ? `${pendingActionTitle} ಬಗ್ಗೆ ತಿಳಿಸಿ`
        : currentLanguage === "gu"
        ? `${pendingActionTitle} વિશે જણાવો`
        : `Tell me about ${pendingActionTitle.toLowerCase()}`;

    result.splice(1, 0, {
      id: `dynamic-action-${Date.now()}`,
      text: dynamicPromptText,
      englishText: `Tell me about ${pendingActionTitle}`,
      isSeasonal: false,
    });
  }

  return result;
}
